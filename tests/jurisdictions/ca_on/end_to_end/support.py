_T657_RESERVE_AMOUNT = re.compile(
    r"^t657_(?:chart_(?P<year>20(?:1[6-9]|2[0-3]))|chart_2024_period_(?P<period>[12])|"
    r"part_(?P<part>[12]))_amount_(?P<letter>[defgij])$"
)


def _t657_reserve_amount(name: str) -> re.Match[str] | None:
    """The match of a name that is a Form T657 amount read from Form T2017, else None: amounts D
    and E of Chart 2016, F and G of Charts 2017 to 2023 and of both periods of Chart 2024, and I
    and J of Parts 1 and 2 of Chart 2025."""
    found = _T657_RESERVE_AMOUNT.match(name)
    if found is None:
        return None
    if found["part"]:
        letters = "ij"
    elif found["year"] == "2016":
        letters = "de"
    else:
        letters = "fg"
    return found if found["letter"] in letters else None


def t657_reserve_rows(**amounts: str) -> dict[int, list[dict[str, str]]]:
    """The Form T2017 rows that make Form T657 read each given amount, by T2017 line.

    Form T657 reads "Amount from line 6 / line 12 of Form T2017" for each year of disposition from
    the T2017 rows (`ca/t2017_reserve_total_for_period`), so a test names the amount it wants and
    this builds the row. Each keyword is the name the amount had when it was an input
    (`t657_chart_2019_amount_f`, `t657_chart_2024_period_1_amount_g`, `t657_part_1_amount_i`) and
    each value the quoted decimal: the letters d, f and i are line 6 (QFFP, a row of line 2) and e,
    g and j line 12 (QSBCS, a row of line 8). A reserve of an earlier year is a disposition that
    many years after, with nothing claimed in 2025: the row's 2024 reserve is the amount. Chart
    2024 and Chart 2025 Part 1 rows answer Period 1 (and, for Part 1, the T5013 slip and a
    partnership year that began before June 25, 2024). The amount
    of Chart 2025 Part 2 is the 2025 reserve claimed, as a negative amount: the row of a
    disposition in 2025 claims it. A zero amount gives no row; a positive Part 2 amount or a
    negative amount of an earlier year is no line 6 or 12 a row can give, and raises ValueError.
    """
    rows: dict[int, list[dict[str, str]]] = {}
    for name, value in amounts.items():
        found = _t657_reserve_amount(name)
        if found is None:
            raise ValueError(f"{name} is not a Form T657 amount read from Form T2017")
        amount = D(value)
        if amount == 0:
            continue
        line = 2 if found["letter"] in "dfi" else 8
        row = {
            "capital_gain": "1000000",
            "payable": "0",
            "proceeds": "1000000",
            "nine_year": "1",
        }
        if found["part"] == "2":
            if amount > 0:
                raise ValueError(f"{name} {value}: a disposition in 2025 has no 2024 reserve")
            # A disposition in 2025: 2025 reserve claimed, up to 90% of a gain of 1,000,000.
            row.update(
                payable="1000000", years="0", claimed=str(-amount), previous="0", period_1="0"
            )
        else:
            if amount < 0:
                raise ValueError(
                    f"{name} {value}: a later year cannot claim more than the year before"
                )
            years = 2025 - int(found["year"]) if found["year"] else 1
            row.update(years=str(years), claimed="0", previous=str(amount))
            if found["period"] == "1" or found["part"] == "1":
                row["period_1"] = "1"
            if found["part"] == "1":
                row["slip"] = "1"
                row["partnership_before"] = "1"
        rows.setdefault(line, []).append(row)
    return rows


def t657_reserve_inputs(reserves: Mapping[str, str], given: Mapping[str, Any]) -> dict[str, Any]:
    """The keywords for `compute` of a return that gives Form T657 amounts read from Form T2017.

    `reserves` are the return's amounts and `given` its other keywords with the test's changes: the
    ones that name a Form T657 amount read from Form T2017 (see `t657_reserve_rows`) replace the
    return's amount of the same name, and are turned into rows of `t2017_rows` after the rows
    `given` has; every other keyword is passed on as it is.
    """
    amounts = {**reserves}
    others: dict[str, Any] = {}
    for name, value in given.items():
        if _t657_reserve_amount(name):
            amounts[name] = value
        else:
            others[name] = value
    rows: dict[int, list[Mapping[str, Any]]] = {
        line: list(rows) for line, rows in (others.get("t2017_rows") or {}).items()
    }
    for line, built in t657_reserve_rows(**amounts).items():
        rows.setdefault(line, []).extend(built)
    return {**others, "t2017_rows": rows}


