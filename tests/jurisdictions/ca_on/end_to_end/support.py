# The Schedule 6 spouse answers of the worked returns: an eligible spouse (line 38101, 1) and the
# spouse's employment income of column 2; a caller's keyword overrides them.
def spouse_inputs(
    spouse_employment_income: str, overrides: Mapping[str, Any] | None = None
) -> dict[str, Any]:
    """The keywords of `starting(...)` for the eligible spouse answers of a return.

    The answer is 1 (an eligible spouse) unless the caller's keywords in `overrides` set the spouse
    on December 31 to 0: a count of 0 with an answer of 1 is an input error, so the answer is 0 too.
    """
    spouse_count = (overrides or {}).get("spouse_or_common_law_partner_on_december_31", 1)
    return {
        "cwb_eligible_spouses": 1 if spouse_count else 0,
        "cwb_spouse_employment_income": spouse_employment_income,
    }


def compute_with_spouse(spouse_employment_income: str, *args: Any, **kwargs: Any) -> Worksheet:
    """The worksheet of `ca-on/return` for `starting(*args, **kwargs)` with the spouse answers."""
    artifacts = starting(*args, **{**spouse_inputs(spouse_employment_income, kwargs), **kwargs})
    return service().compute(CA_ON, 2025, *artifacts)["ca-on/return"][0]
