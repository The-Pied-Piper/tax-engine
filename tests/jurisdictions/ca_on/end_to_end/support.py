def routed_statement(net: str, code: int) -> dict[str, Any]:
    """One Form T2125 statement whose net is `net`, sent to the T1 line of `code` (1 business, 2
    professional, 3 commission). A net of sales is entered as sales; a loss is entered as office
    expenses on no sales, so that line 9946 is the net given."""
    value = D(net)
    if value >= 0:
        business: dict[str, str] = {"gross_sales": net}
    else:
        business = {"gross_sales": "0", "office_expenses": str(-value)}
    return {"business": business, "business_income_line": code}


